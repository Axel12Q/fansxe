CREATE TABLE IF NOT EXISTS google_identities (
 firebase_uid VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 user_id CHAR(32) NOT NULL UNIQUE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS story_highlights (
 id CHAR(32) PRIMARY KEY, user_id CHAR(32) NOT NULL, name VARCHAR(40) NOT NULL,
 cover_asset CHAR(32) NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS highlight_stories (
 highlight_id CHAR(32) NOT NULL, story_id CHAR(32) NOT NULL,
 PRIMARY KEY(highlight_id,story_id),
 FOREIGN KEY(highlight_id) REFERENCES story_highlights(id) ON DELETE CASCADE,
 FOREIGN KEY(story_id) REFERENCES stories(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
